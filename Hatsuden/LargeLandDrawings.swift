import CoreGraphics

/// Original artwork IDs 75–99. Each drawing uses its own body and head outlines.
enum LargeLandDrawings {
    static func draw(id: Int, ink: CrayonCanvas, runFrame: Int? = nil, asleep: Bool = false) {
        let strides: [CGFloat] = [-8, 3, 8, -3]
        let art = Artist(ink: ink, stride: runFrame.map { strides[$0 % strides.count] } ?? 0, asleep: asleep)
        switch id {
        case 75: art.camel()
        case 76: art.zebra()
        case 77: art.donkey()
        case 78: art.horse()
        case 79: art.okapi()
        case 80: art.giraffe()
        case 81: art.serow()
        case 82: art.gazelle()
        case 83: art.reindeer()
        case 84: art.moose()
        case 85: art.muskOx()
        case 86: art.bison()
        case 87: art.wildebeest()
        case 88: art.buffalo()
        case 89: art.rhino()
        case 90: art.hippo()
        case 91: art.lemur()
        case 92: art.ayeAye()
        case 93: art.tarsier()
        case 94: art.marmoset()
        case 95: art.gibbon()
        case 96: art.mandrill()
        case 97: art.chimpanzee()
        case 98: art.orangutan()
        case 99: art.gorilla()
        default: preconditionFailure("Unsupported large land animal artwork ID: \(id)")
        }
    }

    private struct Artist {
        typealias P = (CGFloat, CGFloat)
        let ink: CrayonCanvas
        let stride: CGFloat
        let asleep: Bool

        private let dark: UInt32 = 0x352B30
        private let ivory: UInt32 = 0xFFF0D5

        func shape(_ points: [P], _ fill: UInt32, border: UInt32? = 0x352B30, weight: CGFloat = 4) {
            ink.polygon(points, fill: CrayonCanvas.color(fill), border: border.map(CrayonCanvas.color), weight: weight)
        }

        func oval(_ x: CGFloat, _ y: CGFloat, _ w: CGFloat, _ h: CGFloat, _ fill: UInt32,
                  border: UInt32? = 0x352B30, weight: CGFloat = 4) {
            ink.oval(x, y, w, h, fill: CrayonCanvas.color(fill), border: border.map(CrayonCanvas.color), weight: weight)
        }

        func line(_ points: [P], _ color: UInt32 = 0x352B30, _ width: CGFloat = 3.4) {
            ink.line(points, color: CrayonCanvas.color(color), weight: width)
        }

        func eye(_ x: CGFloat, _ y: CGFloat, size: CGFloat = 7) {
            if asleep {
                line([(x - 3, y + 1), (x + 2, y + 4), (x + 8, y)], dark, max(2, size * 0.4))
            } else {
                oval(x, y, size, size * 1.15, dark, border: nil)
                if size >= 7 { oval(x + 1, y + 1, 2, 2, ivory, border: nil) }
            }
        }

        func leg(_ points: [P], _ fill: UInt32, _ weight: CGFloat, beat: CGFloat, hoof: UInt32 = 0x4B3431) {
            let last = points.count - 1
            let moved: [P] = points.enumerated().map { index, point in
                let travel = index == 0 ? 0 : stride * beat * (index == last ? 1 : 0.32)
                let lift = index == last ? abs(stride) * max(0, beat) * 0.27 : 0
                return (point.0 + travel, point.1 - lift)
            }
            line(moved, dark, weight + 4)
            line(moved, fill, weight)
            if let end = moved.last { line([(end.0 - 5, end.1), (end.0 + 7, end.1 + 1)], hoof, weight * 0.83) }
        }

