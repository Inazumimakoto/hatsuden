/// Original one-at-a-time compositions. Coordinates are on the same
/// 240-point crayon paper as the shop and the wheel sprites.
enum OtherAnimalDrawings {
    static func draw(id: Int, ink: CrayonCanvas, asleep: Bool = false) {
        let drawing = CrayonAnimal(ink: ink, asleep: asleep)
        switch id {
        case 100...131: drawing.drawBird(id)
        case 132...149: drawing.drawReptileOrAmphibian(id)
        case 150...170: drawing.drawSwimmer(id)
        case 189...200: drawing.drawAncientAnimal(id)
        default: preconditionFailure("Unknown animal art ID")
        }
    }
}

