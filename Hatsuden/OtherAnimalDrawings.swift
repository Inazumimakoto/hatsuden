    private func o(_ x: CGFloat, _ y: CGFloat, _ w: CGFloat, _ h: CGFloat,
                   _ fill: Pigment, rim: Bool = true, weight: CGFloat = 3.8) {
        ink.oval(x, y, w, h, fill: CrayonCanvas.color(fill),
                 border: rim ? CrayonCanvas.color(dark) : nil, weight: weight)
    }

    private func p(_ points: [Point], _ fill: Pigment, rim: Bool = true, weight: CGFloat = 3.8) {
        ink.polygon(points, fill: CrayonCanvas.color(fill),
                    border: rim ? CrayonCanvas.color(dark) : nil, weight: weight)
    }

    private func l(_ points: [Point], _ color: Pigment? = nil, _ width: CGFloat = 3) {
        ink.line(points, color: CrayonCanvas.color(color ?? dark), weight: width)
    }

    private func eye(_ x: CGFloat, _ y: CGFloat, size: CGFloat = 8, iris: Pigment? = nil) {
        if asleep {
            let side = max(size, 7)
            l([(x - 2, y - side / 2), (x + side - 2, y - side / 2),
               (x - 2, y + side / 2), (x + side - 1, y + side / 2)], dark, 2.3)
            return
        }
        if let iris { o(x - 2, y - size / 2 - 2, size + 4, size + 4, iris, weight: 1.5) }
        o(x, y - size / 2, size, size, dark, rim: false)
        if size > 6 { o(x + 1.3, y - size / 2 + 1, size * 0.32, size * 0.29, white, rim: false) }
    }

    private func toes(_ x: CGFloat, _ y: CGFloat, _ color: Pigment = 0xE9A15A) {
        l([(x - 8, y + 2), (x, y), (x + 12, y - 2)], dark, 5.2)
        l([(x, y), (x + 7, y + 3)], dark, 4.4)
        l([(x - 7, y + 2), (x, y), (x + 11, y - 2)], color, 2.5)
        l([(x, y), (x + 6, y + 3)], color, 2.0)
    }

    private func leg(_ joints: [Point], _ color: Pigment, width: CGFloat = 7) {
        l(joints, dark, width + 3)
        l(joints, color, width)
    }

    private func dots(_ points: [Point], _ color: Pigment, size: CGFloat = 7) {
        for (x, y) in points {
            o(x, y, size + 1, size, color, rim: false)
        }
    }

    private func drawsStripes(_ strips: [[Point]], _ color: Pigment, width: CGFloat = 4) {
        for stripe in strips { l(stripe, color, width) }
    }

